"""Clang 23 with the SpacemiT X100 model plus LLVM PGO for the K3 lane.

The workspace cross toolchain is the SpacemiT GCC toolchain. This module
implements the reviewed deviation recorded in `environments.lock.yaml`: the
`k3-development` best-achievable lane may use Clang 23 with the upstream
SpacemiT X100 scheduling model and a profile generated on the board, while the
parity tracks keep their locked compilers.

The lane is fail-closed: the compiler, the riscv64 profile runtime, and the
profile data are each verified against the lock before a build starts.
"""

from __future__ import annotations

import stat
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class ClangPgoLock:
    package_version: str
    version_token: str
    compiler_path: Path
    compiler_sha256: str
    triple: str
    sysroot: Path
    gcc_toolchain: Path
    abi: str
    cpu_model: str
    port_flags: str
    profile_runtime_path: Path
    profile_runtime_sha256: str
    profile_runtime_commit: str
    profile_data_path: Path
    profile_data_sha256: str


def _delivery():
    from . import delivery

    return delivery


def locked_port_flags() -> str:
    """Return the port flag set that reproduces the measured configuration."""
    from .manifests import load_clang_pgo_lock

    return load_clang_pgo_lock().port_flags


def prepare_compiler(work_root: Path, evidence: Path) -> Path:
    """Verify the locked lane inputs and return a compiler command wrapper."""
    from .manifests import load_clang_pgo_lock

    delivery = _delivery()
    lock = load_clang_pgo_lock()

    if not lock.compiler_path.is_file():
        raise delivery.ContractError(f"locked clang is missing: {lock.compiler_path}")
    if delivery._sha256(lock.compiler_path) != lock.compiler_sha256:
        raise delivery.ContractError("locked clang executable SHA256 mismatch")
    version_line = delivery._run_command([str(lock.compiler_path), "--version"]).splitlines()[0]
    if lock.version_token not in version_line:
        raise delivery.ContractError(
            f"locked clang version mismatch: {version_line} does not contain "
            f"{lock.version_token}"
        )
    if not lock.profile_runtime_path.is_file():
        raise delivery.ContractError(
            "riscv64 profile runtime is missing; build it from the locked "
            f"compiler-rt commit {lock.profile_runtime_commit}"
        )
    if delivery._sha256(lock.profile_runtime_path) != lock.profile_runtime_sha256:
        raise delivery.ContractError("riscv64 profile runtime SHA256 mismatch")
    if not lock.profile_data_path.is_file():
        raise delivery.ContractError(
            "LLVM profile data is missing; generate it with the instrumented "
            "binary on the board before a best-achievable build"
        )
    if delivery._sha256(lock.profile_data_path) != lock.profile_data_sha256:
        raise delivery.ContractError("LLVM profile data SHA256 mismatch")

    wrapper = work_root / "bin/clang-23-x100-pgo"
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(
        "#!/bin/sh\n"
        "# Generated by coremark_project: locked Clang 23 + X100 + LLVM PGO lane.\n"
        f"exec {lock.compiler_path} --target={lock.triple} --sysroot={lock.sysroot} "
        f"--gcc-toolchain={lock.gcc_toolchain} -mabi={lock.abi} "
        f"-mcpu={lock.cpu_model} -fprofile-use={lock.profile_data_path} \"$@\"\n",
        encoding="utf-8",
    )
    wrapper.chmod(wrapper.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    delivery._write_yaml(
        evidence / "clang-pgo-identity.yaml",
        {
            "lane": "clang23-pgo",
            "compiler": {
                "path": str(lock.compiler_path),
                "sha256": lock.compiler_sha256,
                "version": version_line,
                "package_version": lock.package_version,
            },
            "target": {
                "triple": lock.triple,
                "sysroot": str(lock.sysroot),
                "gcc_toolchain": str(lock.gcc_toolchain),
                "abi": lock.abi,
                "cpu_model": lock.cpu_model,
                "port_flags": lock.port_flags,
            },
            "profile_runtime": {
                "path": str(lock.profile_runtime_path),
                "sha256": lock.profile_runtime_sha256,
                "source_commit": lock.profile_runtime_commit,
            },
            "profile_data": {
                "path": str(lock.profile_data_path),
                "sha256": lock.profile_data_sha256,
            },
            "wrapper": str(wrapper),
        },
    )
    return wrapper
